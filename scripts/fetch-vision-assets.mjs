/**
 * Materialises the two binary assets Glassy is allowed to ship (see CLAUDE.md):
 * the MediaPipe vision wasm runtime and the EfficientDet-Lite0 int8 detector.
 *
 * They are NOT committed — 28MB of binaries would live in git history forever.
 * The wasm is copied out of node_modules (already a dependency); only the model
 * is fetched, and it is pinned to an explicit version rather than "latest" so a
 * build is reproducible and a silently-changed model can't ship unnoticed.
 *
 * Idempotent: skips anything already present with the right size.
 */
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'public', 'vision');
const wasmOutDir = join(outDir, 'wasm');
const wasmSrcDir = join(root, 'node_modules', '@mediapipe', 'tasks-vision', 'wasm');

/** Pinned — do not switch to /latest/, that would make builds non-reproducible. */
const MODEL_URL =
  'https://storage.googleapis.com/mediapipe-models/object_detector/efficientdet_lite0/float16/1/efficientdet_lite0.tflite';
const MODEL_FALLBACK_URL =
  'https://storage.googleapis.com/mediapipe-models/object_detector/efficientdet_lite0/float16/latest/efficientdet_lite0.tflite';
const MODEL_OUT = join(outDir, 'efficientdet_lite0_float16.tflite');
const MODEL_MIN_BYTES = 6_500_000;

const WASM_FILES = [
  'vision_wasm_internal.wasm',
  'vision_wasm_internal.js',
  'vision_wasm_nosimd_internal.wasm',
  'vision_wasm_nosimd_internal.js',
];

async function sizeOf(path) {
  try {
    return (await stat(path)).size;
  } catch {
    return -1;
  }
}

async function copyWasm() {
  await mkdir(wasmOutDir, { recursive: true });
  for (const name of WASM_FILES) {
    const src = join(wasmSrcDir, name);
    const dest = join(wasmOutDir, name);
    const srcSize = await sizeOf(src);
    if (srcSize < 0) {
      throw new Error(
        `Missing ${src}. Run \`npm install\` first — the wasm ships inside @mediapipe/tasks-vision.`,
      );
    }
    if ((await sizeOf(dest)) === srcSize) continue;
    await copyFile(src, dest);
    console.log(`  copied ${name} (${(srcSize / 1024 / 1024).toFixed(1)} MB)`);
  }
}

async function fetchModel() {
  if ((await sizeOf(MODEL_OUT)) >= MODEL_MIN_BYTES) {
    console.log('  model already present, skipping');
    return;
  }
  await mkdir(outDir, { recursive: true });
  let lastError;
  for (const url of [MODEL_URL, MODEL_FALLBACK_URL]) {
    try {
      const response = await fetch(url);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const bytes = Buffer.from(await response.arrayBuffer());
      if (bytes.byteLength < MODEL_MIN_BYTES) {
        throw new Error(`suspiciously small (${bytes.byteLength} bytes)`);
      }
      await writeFile(MODEL_OUT, bytes);
      const sha = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
      console.log(
        `  fetched model (${(bytes.byteLength / 1024 / 1024).toFixed(1)} MB, sha256:${sha}…) from ${url}`,
      );
      return;
    } catch (err) {
      lastError = err;
      console.warn(`  ${url} failed: ${err.message}`);
    }
  }
  throw new Error(`Could not fetch the detector model: ${lastError?.message}`);
}

console.log('Materialising vision assets…');
await copyWasm();
await fetchModel();

// Leave a manifest so the app can sanity-check what shipped without guessing.
await writeFile(
  join(outDir, 'assets.json'),
  `${JSON.stringify(
    {
      model: 'efficientdet_lite0_float16.tflite',
      modelBytes: await sizeOf(MODEL_OUT),
      wasmDir: 'wasm',
      note: 'Generated by scripts/fetch-vision-assets.mjs. Not committed.',
    },
    null,
    2,
  )}\n`,
);

const total = (await readFile(MODEL_OUT)).byteLength + (await sizeOf(join(wasmOutDir, 'vision_wasm_internal.wasm')));
console.log(`Done. Largest single download for a user: ~${(total / 1024 / 1024).toFixed(0)} MB uncompressed.`);
